    internal static IReadOnlyDictionary<string, string> Catalog(string language) => language switch
    {
        "fr-BE" => French,
        "nl-BE" => Dutch,
        _ => English
    };

    public static string Get(string key, string? language = null)
    {
        var code = language ?? LocalizationService.DefaultLanguage;
        code = code.StartsWith("fr", StringComparison.OrdinalIgnoreCase) ? "fr-BE"
            : code.StartsWith("nl", StringComparison.OrdinalIgnoreCase) ? "nl-BE"
            : "en";

        var values = code switch
        {
            "fr-BE" => French,
            "nl-BE" => Dutch,
            _ => English
        };

        if (values.TryGetValue(key, out var value)) return value;
        return English.TryGetValue(key, out value) ? value : $"[{key}]";
    }

